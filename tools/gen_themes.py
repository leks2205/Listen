#!/usr/bin/env python3
"""Generate crates/listen-core/src/theme/palettes.rs from Feishin's theme files.

Usage: tools/gen_themes.py /path/to/feishin > crates/listen-core/src/theme/palettes.rs
Themes are merged onto Feishin's `default.ts` colors, like `app-theme.ts` does.
"""
import re, sys, pathlib

root = pathlib.Path(sys.argv[1]) / "src/shared/themes"
enum_src = (root / "app-theme-types.ts").read_text()
ids = re.findall(r"(\w+) = '(\w+)',", enum_src)
KEYS = ["background", "background-alternate", "foreground", "foreground-muted", "primary",
        "state-error", "state-info", "state-success", "state-warning", "surface", "surface-foreground"]

def parse(text):
    block = re.search(r"colors:\s*\{(.*?)\}", text, re.S)
    colors = dict(re.findall(r"'?([\w-]+)'?:\s*'([^']+)'", block.group(1))) if block else {}
    mode = re.search(r"mode:\s*'(dark|light)'", text)
    return colors, mode.group(1) if mode else "dark"

def rgb(s):
    m = re.match(r"rgba?\(\s*(\d+),?\s+(\d+),?\s+(\d+)", s) or re.match(r"rgba?\((\d+),\s*(\d+),\s*(\d+)", s)
    if m:
        return tuple(int(x) for x in m.groups())
    m = re.match(r"#([0-9a-fA-F]{6})", s)
    if m:
        h = m.group(1)
        return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))
    raise ValueError(s)

base, _ = parse((root / "default.ts").read_text())
out = ["// @generated by tools/gen_themes.py from Feishin's src/shared/themes (GPL-3.0). Do not edit.",
       "use super::{Palette, Rgb, ThemeMode};", "",
       "pub const PALETTES: &[(&str, &str, Palette)] = &["]
for enum_name, theme_id in ids:
    kebab = re.sub(r"(?<!^)(?=[A-Z])", "-", theme_id).lower()
    files = list((root / kebab).glob("*.ts"))
    if not files:
        continue
    colors, mode = parse(files[0].read_text())
    merged = {**base, **colors}
    fields = ",\n".join(
        f"            {k.replace('-', '_')}: Rgb{rgb(merged[k])}" for k in KEYS)
    label = re.sub(r"(?<!^)(?=[A-Z])", " ", theme_id).title()
    out.append(f'    ("{theme_id}", "{label}", Palette {{\n            mode: ThemeMode::{mode.title()},\n{fields},\n        }}),')
out.append("];")
print("\n".join(out))
