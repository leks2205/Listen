#!/usr/bin/env python3
"""Regenerate app/src/icons.rs from the SVGs in assets/icons (run from the repo root).

New Remix icons must come from remixicon@4.8.0: later releases are not under Apache-2.0."""
import os, re

files = sorted(f for f in os.listdir("assets/icons") if f.endswith(".svg"))
camel = lambda f: "".join(p.capitalize() for p in f[:-4].split("-"))
variants = "\n".join(f"    {camel(f)}," for f in files)
all_list = "\n".join(f"    Icon::{camel(f)}," for f in files)
arms = "\n".join(f'        Icon::{camel(f)} => include_bytes!("../../assets/icons/{f}"),' for f in files)
open("app/src/icons.rs", "w").write(f'''//! Embedded SVG icons (Remix Icon, Apache-2.0; Lucide, ISC; Simple Icons, CC0) — the same
//! glyphs Feishin uses. `Ri*` = Remix, `Lu*` = Lucide, `Si*` = Simple Icons.
// @generated by tools/gen_icons.py; add files to assets/icons and rerun.

use iced::widget::svg::Handle;
use std::sync::LazyLock;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Icon {{
{variants}
}}

const ALL: &[Icon] = &[
{all_list}
];

fn bytes(icon: Icon) -> &'static [u8] {{
    match icon {{
{arms}
    }}
}}

static HANDLES: LazyLock<Vec<Handle>> =
    LazyLock::new(|| ALL.iter().map(|&i| Handle::from_memory(bytes(i))).collect());

impl Icon {{
    /// A cached handle; cloning is cheap (reference-counted).
    pub fn handle(self) -> Handle {{
        // `ALL` lists the variants in declaration order.
        HANDLES[self as usize].clone()
    }}
}}
''')
